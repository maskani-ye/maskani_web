/**
 * رابط واتساب برسالةٍ مُهيّأة — **مصدر واحد لصياغتها**.
 *
 * ⚠️ **المحادثة الفارغة تُضيّع الطرفين.** كان الزرّ يفتح واتساب بلا نصّ، فيبدأ
 * الباحث بـ«السلام عليكم» ويردّ المُعلِن «أيّ عقار؟» — وهو ينشر عشرات. الرسالة
 * المُهيّأة تحمل **العنوان والسعر والمدينة والرابط**، فيعرف المُعلِن الموضوع من
 * أوّل سطر ويفتح الصفحة إن شاء.
 *
 * ⚠️ **والرابط جزءٌ من الرسالة لا زينة**: هو ما يُعيد المُعلِن إلى المنصّة،
 * ويجعل المحادثة قابلةً للمتابعة بعد أيّام حين يُنسى أيّ إعلانٍ كان.
 *
 * ⚠️ **ولا يُكتب في الرسالة ما لا نعرفه.** الحقول الاختيارية تُحذف إن غابت بدل
 * كتابة «غير محدّد» — سطرٌ فارغ المعنى يُطيل الرسالة ولا يُفيد.
 */

/** أقصى طول للنصّ المُهيّأ — ما بعده تبترُه بعض العملاء بلا إنذار. */
const MAX_TEXT = 900;

export interface WaContext {
  /** عنوان الإعلان كما يظهر للمستخدم. */
  title?: string | null;
  /** السعر مُنسَّقاً بعملته (تُمرَّر جاهزة — التنسيق ليس مسؤولية هذا الملفّ). */
  price?: string | null;
  /** المدينة أو الحيّ. */
  place?: string | null;
  /** رقم الإعلان — يُسهّل على المُعلِن البحث في سجلّه. */
  ref?: string | number | null;
  /** الرابط العامّ للإعلان. */
  url?: string | null;
  /**
   * وصف النوع **بصيغته الكاملة المطابِقة**: «العقار المعروض» · «الخدمة
   * المعروضة». يُمرَّر كاملاً لا كاسمٍ مفرد، لأنّ إلصاق «المعروض» في القالب
   * يُنتج «الخدمة المعروض» — والمؤنّث والمذكّر لا يُعالَجان بسلسلةٍ واحدة.
   */
  kind?: string;
}

/** نصّ الرسالة وحده (بلا ترميز) — مكشوف للاختبار وإعادة الاستعمال. */
export function waMessage(ctx: WaContext): string {
  const kind = ctx.kind || "الإعلان المعروض";
  const lines: string[] = [`السلام عليكم، أتواصل معك بخصوص ${kind} على مسكني:`];

  if (ctx.title) lines.push(`▪️ ${ctx.title}`);

  // فاصلٌ نقطيّ لا شَرطة: المدينة والحيّ بينهما شَرطة أصلاً، فتتوالى شَرطتان
  // («٣٣٬٠٠٠ ج.م — القاهرة — المعادي») فلا يُعرف أين ينتهي السعر.
  const meta = [ctx.price, ctx.place].filter(Boolean).join(" · ");
  if (meta) lines.push(meta);
  if (ctx.ref) lines.push(`رقم الإعلان: #${ctx.ref}`);
  if (ctx.url) lines.push("", ctx.url);

  const text = lines.join("\n");
  return text.length > MAX_TEXT ? `${text.slice(0, MAX_TEXT - 1)}…` : text;
}

/**
 * رابط `wa.me` كامل. يُعيد `null` إن لم يبقَ من الرقم أرقامٌ صالحة — فلا
 * يُعرض زرٌّ يفتح واتساب على رقمٍ فارغ.
 */
export function waHref(phone: string | null | undefined, ctx: WaContext): string | null {
  const digits = (phone || "").replace(/\D/g, "");
  if (digits.length < 8) return null;
  return `https://wa.me/${digits}?text=${encodeURIComponent(waMessage(ctx))}`;
}
